#!/usr/bin/env python3
"""Generates shared/src/i18n/strings.gen.ts from the Android strings.xml files (fr default, ar),
so the TV editions show exactly the texts of the Android app. Run after changing the Android strings."""
import html, json, os, re, xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, '..', 'app', 'src', 'main', 'res')

def load(path):
    out = {}
    for el in ET.parse(path).getroot():
        if el.tag != 'string' or el.get('translatable') == 'false' and False:
            continue
        name = el.get('name')
        text = ''.join(el.itertext())
        # Android escapes
        text = text.replace("\\'", "'").replace('\\"', '"').replace('\\n', '\n').replace('\\t', '\t').replace('\\@', '@').replace('\\?', '?')
        if len(text) >= 2 and text[0] == '"' and text[-1] == '"':
            text = text[1:-1]
        out[name] = text
    return out

fr = load(os.path.join(RES, 'values', 'strings.xml'))
ar = load(os.path.join(RES, 'values-ar', 'strings.xml'))
missing_ar = sorted(k for k in fr if k not in ar)
dst = os.path.join(ROOT, 'shared', 'src', 'i18n', 'strings.gen.ts')
with open(dst, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/strings_to_ts.py from app/src/main/res/values*/strings.xml. Do not edit.\n')
    f.write('export const fr = ' + json.dumps(fr, ensure_ascii=False, indent=1, sort_keys=True) + ' as const;\n')
    f.write('export const ar: Partial<Record<keyof typeof fr, string>> = ' + json.dumps(ar, ensure_ascii=False, indent=1, sort_keys=True) + ';\n')
print(f'{len(fr)} strings (fr), {len(ar)} (ar), missing in ar: {len(missing_ar)}')
