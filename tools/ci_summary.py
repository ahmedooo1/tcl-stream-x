#!/usr/bin/env python3
"""Builds RESULTS.md (release notes) from unit-test XML, device reports and catalog checks."""
import glob
import json
import os
import xml.etree.ElementTree as ET

out = ["# TCL Stream X: CI results\n"]

tests = fails = skipped = 0
failed_names = []
for f in glob.glob("app/build/test-results/testDebugUnitTest/*.xml"):
    root = ET.parse(f).getroot()
    tests += int(root.get("tests", 0))
    skipped += int(root.get("skipped", 0))
    for tc in root.iter("testcase"):
        if tc.find("failure") is not None or tc.find("error") is not None:
            fails += 1
            failed_names.append(f"{tc.get('classname', '').split('.')[-1]}.{tc.get('name')}")
out.append(f"## Unit tests (JVM)\n\n{tests - fails - skipped} passed, {fails} failed, {skipped} skipped.")
out += [f"- FAILED {n}" for n in failed_names]

def load(p):
    try:
        return json.load(open(p, encoding="utf-8"))
    except (OSError, ValueError):
        return None

for cls in ["ImportOnDeviceTest", "XtreamOnDeviceTest", "PlaybackOnDeviceTest", "PhoneTourTest", "UiTourTest"]:
    p = f"ci-out/{cls}.txt"
    if os.path.exists(p):
        ok = any(l.startswith("OK (") for l in open(p, encoding="utf-8", errors="replace"))
        out.append(f"\n- Emulator `{cls}`: {'passed' if ok else 'FAILED'}")

if os.path.exists("ci-out/device.txt"):
    dev = " / ".join(l.strip() for l in open("ci-out/device.txt", encoding="utf-8") if l.strip())
    out.append(f"\nEmulator used for device tests: {dev}")
out.append("\n# A. Synthetic performance tests (generated data, no real content)\n")
out.append("Every number in this part comes from data generated by the tests themselves (fake names, fake categories, "
           "a panel simulated on the machine). It measures speed and memory, not whether any real source works.")
jvm = load("app/build/perf/xtream-jvm.json")
if jvm:
    out.append(f"\n### Xtream panel parsing (JVM unit test)\n\n{jvm['live']:,} live + {jvm['movies']:,} films + {jvm['series']:,} series "
               f"({jvm['bytes']/1048576:.1f} MB of JSON) streamed and mapped in {jvm['elapsedMs']/1000:.1f} s, heap growth about {jvm['heapGrowthMb']} MB.")
imp = load("ci-out/import-report.json")
if imp:
    out.append(f"\n### Large M3U import (emulator)\n\n{imp['channels']:,} channels, {imp['fileMb']} MB file: imported in {imp['importMs']/1000:.1f} s, "
               f"heap delta {imp['heapDeltaMb']} MB, group page query {imp['groupPageQueryMs']} ms, search {imp['searchMs']} ms.")
xi = load("ci-out/xtream-import-report.json")
if xi:
    out.append(f"\n### Xtream account import (emulator, simulated panel)\n\n{xi['live']:,} live + {xi['movies']:,} films + {xi['series']:,} series "
               f"({xi['panelMb']} MB of API answers) imported into Room in {xi['importMs']/1000:.1f} s, heap delta {xi['heapDeltaMb']} MB. "
               f"Queries on the full library: {xi['regions']} countries/languages in {xi['regionsMs']} ms, first page of one country {xi['regionPageMs']} ms, "
               f"300 film categories {xi['groupsMs']} ms, film search {xi['searchMs']} ms, next channel (zapping) {xi['zapQueryMs']} ms, "
               f"series seasons/episodes on demand {xi['seriesInfoMs']} ms.")

out.append("\n# B. Real playback with authorized sources\n")
out.append("Real streams played by the app's own player on the emulator: official free channels of the built-in catalog and openly "
           "licensed test media. No subscription account was used.")
xp = load("ci-out/xtream-playback-report.json")
if xp:
    out.append("\n### Account path (reference, login decrypted in memory, panel redirect, player)\n")
    out.append(f"The simulated panel redirected {xp['panelStreamRequests']} stream requests to openly licensed media "
               f"(live: Apple BipBop HLS, films and episodes: Blender open movie).\n")
    out.append("| Kind | Playing | Ready after | Time playing |")
    out.append("|---|---|---|---|")
    for r in xp["results"]:
        out.append(f"| {r['kind']} | {'yes' if r['ready'] else 'no'} | {r['readyMs']} ms | {r['playingMs']/1000:.1f} s |")
    if xp.get("vodSkipped"):
        out.append("| movie, episode | skipped: no open MP4 reachable from CI in this run | | |")

pb = load("ci-out/playback-report.json")
if pb:
    out.append(f"\n### Built-in channels and open media ({pb['device']})\n")
    out.append("| Stream | Group | Ready | Time playing | First frame | Video | Quality options | Audio | Subtitles | Error |")
    out.append("|---|---|---|---|---|---|---|---|---|---|")
    for r in pb["results"]:
        out.append(f"| {r['name']} | {r['group']} | {'yes' if r['ready'] else 'no'} ({r['readyMs']} ms) | {r["advancedMs"]/1000:.1f} s | "
                   f"{'yes' if r['firstFrameRendered'] else 'no'} | {r['video']} | {r['qualityOptions']} | {r['audioTracks']} | {r['textOptions']} | {r.get('error', '')} |")

if os.path.exists("catalog/REPORT.md"):
    # Only the totals go in the notes (release notes are capped at 125 000 characters); REPORT.md is attached.
    rep = open("catalog/REPORT.md", encoding="utf-8").read().splitlines()
    head = [l for l in rep[:6] if l.strip() and not l.startswith("|")]
    from collections import Counter
    statuses = Counter(l.split("|")[3].strip() for l in rep if l.startswith("| ") and l.count("|") >= 5 and not l.startswith("| Channel"))
    out.append("\n" + "\n".join(head).replace("# Built-in catalog check", "## Built-in catalog check (from CI)"))
    out.append("\nResults: " + ", ".join(f"{k} {v}" for k, v in statuses.most_common()) + ". Full table: REPORT.md attached to this release.")
if os.path.exists("catalog/SOURCES_REPORT.md"):
    out.append("\n" + open("catalog/SOURCES_REPORT.md", encoding="utf-8").read().replace("# Source probe", "## Other sources (from CI)"))

open("RESULTS.md", "w", encoding="utf-8").write("\n".join(out) + "\n")
print("\n".join(out)[:3000])
